import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../thrivesight_core/nts/structure.json", import.meta.url);
const copy = new URL("../src/core/structure.json", import.meta.url);
const text = readFileSync(source, "utf8");

if (process.argv.includes("--check")) {
  if (readFileSync(copy, "utf8") !== text) {
    console.error("web/src/core/structure.json differs from the Lean export. Run `npm run sync`.");
    process.exit(1);
  }
} else {
  writeFileSync(copy, text);
}

const promptSource = new URL("../../thrivesight_core/nts/prompts/salience.md", import.meta.url);
const promptCopy = new URL("../src/core/salience-prompt.ts", import.meta.url);
const promptText = `// Generated by scripts/sync-structure.mjs from thrivesight_core/nts/prompts/salience.md. Do not edit.\nexport const SALIENCE_PROMPT = ${JSON.stringify(readFileSync(promptSource, "utf8"))};\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(promptCopy, "utf8") !== promptText) {
    console.error("web/src/core/salience-prompt.ts differs from the prompt. Run `npm run sync`.");
    process.exit(1);
  }
} else {
  writeFileSync(promptCopy, promptText);
}
